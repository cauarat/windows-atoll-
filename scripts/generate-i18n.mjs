#!/usr/bin/env node
// Writes every translation table in the repository from one catalogue.
//
// Three platforms read the same strings and none of them can read the others'
// format: the Mac wants .lproj/Localizable.strings, the Tauri frontend wants a
// module it can import, and the tray lives in Rust. Hand-keeping three copies
// of six hundred strings is the kind of table where one side gains an entry and
// nobody notices for a release -- the same reason scripts/generate-mochi-shapes.mjs
// exists. i18n/catalog.json is the source; everything below is generated.
//
//   node scripts/generate-i18n.mjs            # check only, exits 1 if stale
//   node scripts/generate-i18n.mjs --write    # rewrite the generated files

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WRITE = process.argv.includes("--write");

/** English is the key itself, so it is not stored and cannot drift from it. */
export const LANGS = ["en", "es", "pt-BR"];

export function loadCatalog(root = ROOT) {
  const raw = JSON.parse(readFileSync(join(root, "i18n", "catalog.json"), "utf8"));
  // Drop the leading "//" comment keys the file uses to group its sections.
  return Object.fromEntries(Object.entries(raw).filter(([k]) => !k.startsWith("//")));
}

export function valueFor(entry, key, lang) {
  if (lang === "en") return entry.en ?? key;
  return entry[lang] ?? key;
}

const GEN = "Generated by scripts/generate-i18n.mjs -- do not edit by hand.";

// MARK: - .strings

const stringsEscape = (s) =>
  s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n");

function stringsFile(catalog, lang) {
  const lines = [`/* ${GEN} */`, ""];
  for (const [key, entry] of Object.entries(catalog)) {
    lines.push(`"${stringsEscape(key)}" = "${stringsEscape(valueFor(entry, key, lang))}";`);
  }
  return lines.join("\n") + "\n";
}

// MARK: - TypeScript

function tsFile(catalog) {
  const body = Object.entries(catalog)
    .map(([key, entry]) => {
      const pairs = LANGS.filter((l) => l !== "en")
        .map((l) => `${JSON.stringify(l)}: ${JSON.stringify(valueFor(entry, key, l))}`)
        .join(", ");
      return `  ${JSON.stringify(key)}: { ${pairs} },`;
    })
    .join("\n");
  return `// ${GEN}

/** Every translated string, keyed by its English original. */
export const CATALOG: Record<string, Record<string, string>> = {
${body}
};
`;
}

// MARK: - Rust

const rustEscape = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"');

function rustFile(catalog) {
  const arm = (lang) =>
    Object.entries(catalog)
      .map(([key, entry]) => {
        const v = valueFor(entry, key, lang);
        return v === key ? null : `            "${rustEscape(key)}" => Some("${rustEscape(v)}"),`;
      })
      .filter(Boolean)
      .join("\n");

  return `// ${GEN}

//! The tray menu and the error strings the island shows are built here in Rust,
//! so they need the catalogue too. \`None\` means "no translation", and every
//! caller falls back to the English key it passed in.

/// The translation of \`key\` into \`lang\`, or \`None\` to keep the English.
pub fn lookup(lang: &str, key: &str) -> Option<&'static str> {
    match lang {
${LANGS.filter((l) => l !== "en")
  .map((l) => `        "${l}" => match key {\n${arm(l)}\n            _ => None,\n        },`)
  .join("\n")}
        _ => None,
    }
}
`;
}

// MARK: - Run

const OUTPUTS = (catalog) => [
  ...LANGS.map((lang) => [
    join("NotchBuddy", "Resources", "Localizations", `${lang}.lproj`, "Localizable.strings"),
    stringsFile(catalog, lang),
  ]),
  [join("windows", "src", "core", "i18n.generated.ts"), tsFile(catalog)],
  [join("windows", "src-tauri", "src", "i18n_generated.rs"), rustFile(catalog)],
];

if (import.meta.url === `file://${process.argv[1]}`) {
  const catalog = loadCatalog();
  let stale = [];
  for (const [rel, body] of OUTPUTS(catalog)) {
    const path = join(ROOT, rel);
    if (WRITE) {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, body);
    } else if (!existsSync(path) || readFileSync(path, "utf8") !== body) {
      stale.push(rel);
    }
  }
  const n = Object.keys(catalog).length;
  if (WRITE) {
    console.log(`  ${n} strings → ${OUTPUTS(catalog).length} generated files`);
  } else if (stale.length) {
    console.error("  ! generated translation files are out of date:");
    for (const f of stale) console.error(`      ${f}`);
    console.error("    run: node scripts/generate-i18n.mjs --write");
    process.exit(1);
  } else {
    console.log(`  ${n} strings, generated files up to date`);
  }
}
